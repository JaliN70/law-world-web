export function mojSingle(pcode, flno) {
  const f = String(flno).replace(/\s+/g, '');
  return `https://law.moj.gov.tw/LawClass/LawSingle.aspx?pcode=${pcode}&flno=${encodeURIComponent(f)}`;
}

export function mojAll(pcode) {
  return `https://law.moj.gov.tw/LawClass/LawAll.aspx?pcode=${pcode}`;
}

